/// The parts of a composite: `Aacute` gives `["A", "acutecomb"]`. Production-style
/// (`Aacute`) and `uniXXXX` names are both understood; suffixed names have no recipe.
pub fn parts(name: &str) -> Option<&'static [&'static str]> {
    let cp = glyphdata::codepoint_for_name(name)?;
    DECOMPOSITIONS
        .iter()
        .find(|(c, _, _)| *c == cp)
        .map(|(_, _, p)| *p)
}

/// The code point a composite's production-style name stands for (`Aacute` → U+00C1).
pub fn codepoint(name: &str) -> Option<u32> {
    DECOMPOSITIONS
        .iter()
        .find(|(_, n, _)| *n == name)
        .map(|(c, _, _)| *c)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn recipes_resolve_both_name_styles() {
        assert_eq!(parts("Aacute"), Some(["A", "acutecomb"].as_slice()));
        assert_eq!(parts("uni00C1"), Some(["A", "acutecomb"].as_slice()));
        assert_eq!(
            parts("Acircumflexacute"),
            Some(["A", "circumflexcomb", "acutecomb"].as_slice())
        );
        assert_eq!(parts("AEacute"), Some(["AE", "acutecomb"].as_slice()));
        assert_eq!(parts("A"), None);
        assert_eq!(parts("Aacute.alt"), None);
        assert_eq!(codepoint("Aacute"), Some(0xC1));
        assert_eq!(codepoint("nope"), None);
    }
}
